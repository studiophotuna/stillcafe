export function AdminNav({ vertical = false }: { vertical?: boolean }) {
  const pathname = usePathname();
  return (
    <nav
      className={
        vertical ? "flex flex-col gap-1" : "flex gap-0.5 overflow-x-auto"
      }
    >
      {LINKS.map((l) => {
        const active =
          l.href === "/admin"
            ? pathname === "/admin"
            : pathname.startsWith(l.href);
        return (
          <Link
            key={l.href}
            href={l.href}
            className={
              vertical
                ? `flex items-center gap-2.5 rounded-lg px-3 py-2 text-sm font-medium transition-colors ${
                    active
                      ? "bg-maroon/10 text-maroon"
                      : "text-espresso/55 hover:bg-sand/60 hover:text-espresso"
                  }`
                : `flex items-center gap-1.5 whitespace-nowrap rounded-lg px-3 py-1.5 text-sm font-medium transition-colors ${
                    active
                      ? "bg-maroon/10 text-maroon"
                      : "text-espresso/50 hover:bg-sand/50 hover:text-espresso/70"
                  }`
            }
          >
            <NavIcon icon={l.icon} />
            <span className={vertical ? "" : "hidden sm:inline"}>
              {l.label}
            </span>
          </Link>
        );
      })}
    </nav>
  );
}
